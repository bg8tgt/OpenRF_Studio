_BY_ID = {p["id"]: p for p in _PERSONAS}
_BY_NAME = {p["name"]: p for p in _PERSONAS}


def all_personas():
    """返回角色清单（不含大段 prompt，给界面下拉框用）。"""
    return [{"id": p["id"], "name": p["name"], "title": p["title"],
             "summary": p["summary"]} for p in _PERSONAS]


def names():
    return [p["name"] for p in _PERSONAS]


def resolve(key):
    """接受 id 或中文名，返回完整角色 dict；认不出返回默认角色。"""
    if not key:
        return _BY_ID[DEFAULT_PERSONA]
    k = str(key).strip()
    return _BY_ID.get(k) or _BY_NAME.get(k) or _BY_ID[DEFAULT_PERSONA]


def compose(base_prompt, persona_key=None):
    """把角色设定接在主系统提示词前面。

    角色段只谈立场与判断习惯，明确声明"不改变下面的输出协议"，
    避免模型为了演好角色而破坏 JSON 格式。
    """
    base = (base_prompt or "").strip()
    if not persona_key:
        return base
    p = resolve(persona_key)
    head = p["prompt"].strip()
    if not base:
        return head
    return (head + chr(10) + chr(10)
            + "以下输出协议与动作格式的约束优先于角色设定，不得为了贴合身份而违反：" + chr(10)
            + chr(10) + base)
